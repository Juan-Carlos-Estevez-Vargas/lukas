import { strToU8, zipSync } from "fflate";

/**
 * Cuaderno .xlsx mínimo (SpreadsheetML) escrito a mano y comprimido con `fflate`. Los montos van
 * como texto decimal exacto en la celda numérica: nunca pasan por punto flotante.
 */
export type Cell =
  | { readonly t: "text"; readonly v: string; readonly bold?: boolean }
  | { readonly t: "money"; readonly v: string }
  | null;

export interface Sheet {
  readonly name: string;
  readonly rows: readonly (readonly Cell[])[];
  /** Ancho de cada columna en caracteres. */
  readonly widths?: readonly number[];
}

export const text = (v: string, bold = false): Cell => ({ t: "text", v, bold });
export const money = (decimal: string): Cell => ({ t: "money", v: decimal });

const xmlEscape = (s: string) =>
  s
    // Caracteres de control que XML no admite.
    // biome-ignore lint/suspicious/noControlCharactersInRegex: se quitan a propósito.
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

const column = (i: number): string => {
  let n = i + 1;
  let out = "";
  while (n > 0) {
    const r = (n - 1) % 26;
    out = String.fromCharCode(65 + r) + out;
    n = Math.floor((n - 1) / 26);
  }
  return out;
};

/** Excel no deja ciertos caracteres ni más de 31 en el nombre, y no admite nombres repetidos. */
export function sheetNames(names: readonly string[]): string[] {
  const used = new Set<string>();
  return names.map((raw) => {
    const base =
      raw
        .replace(/[[\]:*?/\\']/g, " ")
        .trim()
        .slice(0, 31) || "Hoja";
    let name = base;
    for (let n = 2; used.has(name.toLowerCase()); n++) {
      const suffix = ` (${n})`;
      name = base.slice(0, 31 - suffix.length) + suffix;
    }
    used.add(name.toLowerCase());
    return name;
  });
}

